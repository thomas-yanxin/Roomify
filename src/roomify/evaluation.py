"""Source-isolated holdout evaluation for Roomify predictions.

Ground-truth files deliberately use a small annotation schema instead of the
production schema.  Keep them outside this repository; only predictions may
be generated by Roomify.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Literal, Self

from pydantic import Field, model_validator
from shapely.geometry import GeometryCollection, LineString, Polygon, box
from shapely.ops import unary_union
from shapely.validation import make_valid

from roomify.schema import (
    EXTERIOR,
    UNKNOWN,
    BBox,
    ElementType,
    FloorPlan,
    Point,
    StrictModel,
)

PROTOCOL_VERSION = "1.0"
ROOM_MATCH_IOU = 0.5
OPENING_MATCH_IOU = 0.5
WALL_TOLERANCE_RATIO = 0.003


class TruthRoom(StrictModel):
    id: str = Field(min_length=1)
    polygon_px: list[Point] = Field(min_length=3)

    @model_validator(mode="after")
    def _valid_polygon(self) -> Self:
        polygon = _polygon(self.polygon_px)
        if not polygon.is_valid or polygon.area <= 0:
            raise ValueError(f"room {self.id}: polygon must be valid and non-empty")
        return self


class TruthWall(StrictModel):
    start_px: Point
    end_px: Point

    @model_validator(mode="after")
    def _positive_length(self) -> Self:
        if _line(self.start_px, self.end_px).length <= 0:
            raise ValueError("truth wall endpoints must differ")
        return self


class TruthOpening(StrictModel):
    element_type: ElementType
    bbox_px: BBox
    connects: tuple[str, str]


class HoldoutTruth(StrictModel):
    protocol_version: Literal["1.0"] = PROTOCOL_VERSION  # type: ignore[assignment]
    source_group: str = Field(min_length=1)
    image_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    image_width_px: int = Field(gt=0)
    image_height_px: int = Field(gt=0)
    orthogonal: bool = True
    rooms: list[TruthRoom]
    walls: list[TruthWall]
    openings: list[TruthOpening]

    @model_validator(mode="after")
    def _references_exist(self) -> Self:
        room_ids = [room.id for room in self.rooms]
        if len(room_ids) != len(set(room_ids)):
            raise ValueError("truth room ids must be unique")
        if self.orthogonal:
            for room in self.rooms:
                points = room.polygon_px
                if any(
                    start.x != end.x and start.y != end.y
                    for start, end in zip(points, points[1:] + points[:1], strict=True)
                ):
                    raise ValueError(f"room {room.id}: diagonal edge in orthogonal truth")
        allowed = set(room_ids) | {EXTERIOR}
        for opening in self.openings:
            bad = set(opening.connects) - allowed
            if bad:
                raise ValueError(f"truth opening references unknown rooms: {sorted(bad)}")
        return self


class ReleaseGates(StrictModel):
    protocol_version: Literal["1.0"] = PROTOCOL_VERSION  # type: ignore[assignment]
    minimum_cases: int = Field(ge=1)
    minimum_source_groups: int = Field(ge=2)
    room_iou: float = Field(ge=0, le=1)
    wall_f1: float = Field(ge=0, le=1)
    opening_f1: float = Field(ge=0, le=1)
    adjacency_f1: float = Field(ge=0, le=1)
    physical_violation_rate: float = Field(ge=0, le=1)


def _polygon(points: list[Point]) -> Polygon:
    return Polygon([(point.x, point.y) for point in points])


def _line(start: Point, end: Point) -> LineString:
    return LineString(((start.x, start.y), (end.x, end.y)))


def _max_assignment(weights: list[list[float]]) -> list[tuple[int, int]]:
    """Maximum-weight one-to-one assignment (Hungarian, padded to square)."""
    if not weights or not weights[0]:
        return []
    rows, columns = len(weights), len(weights[0])
    size = max(rows, columns)
    costs = [
        [1.0 - (weights[i][j] if i < rows and j < columns else 0.0) for j in range(size)]
        for i in range(size)
    ]
    u = [0.0] * (size + 1)
    v = [0.0] * (size + 1)
    matching = [0] * (size + 1)
    previous = [0] * (size + 1)
    for row in range(1, size + 1):
        matching[0] = row
        column = 0
        minimum = [math.inf] * (size + 1)
        used = [False] * (size + 1)
        while True:
            used[column] = True
            current_row = matching[column]
            delta, next_column = math.inf, 0
            for candidate in range(1, size + 1):
                if used[candidate]:
                    continue
                reduced = costs[current_row - 1][candidate - 1] - u[current_row] - v[candidate]
                if reduced < minimum[candidate]:
                    minimum[candidate] = reduced
                    previous[candidate] = column
                if minimum[candidate] < delta:
                    delta, next_column = minimum[candidate], candidate
            for candidate in range(size + 1):
                if used[candidate]:
                    u[matching[candidate]] += delta
                    v[candidate] -= delta
                else:
                    minimum[candidate] -= delta
            column = next_column
            if matching[column] == 0:
                break
        while True:
            next_column = previous[column]
            matching[column] = matching[next_column]
            column = next_column
            if column == 0:
                break
    return [
        (matching[column] - 1, column - 1)
        for column in range(1, size + 1)
        if 0 < matching[column] <= rows and column <= columns
    ]


def _f1(true_positive: float, predicted: float, expected: float) -> float:
    if predicted == 0 and expected == 0:
        return 1.0
    precision = true_positive / predicted if predicted else 0.0
    recall = true_positive / expected if expected else 0.0
    return 2 * precision * recall / (precision + recall) if precision + recall else 0.0


def _room_scores(
    plan: FloorPlan, truth: HoldoutTruth
) -> tuple[float, dict[str, str], list[list[float]]]:
    predicted = []
    for room in plan.rooms:
        polygon = _polygon(room.polygon_px)
        predicted.append(polygon if polygon.is_valid else make_valid(polygon))
    expected = [_polygon(room.polygon_px) for room in truth.rooms]
    weights = [
        [
            left.intersection(right).area / left.union(right).area
            if left.union(right).area
            else 0.0
            for right in expected
        ]
        for left in predicted
    ]
    pairs = _max_assignment(weights)
    denominator = max(len(predicted), len(expected))
    score = sum(weights[i][j] for i, j in pairs) / denominator if denominator else 1.0
    mapping = {
        plan.rooms[i].id: truth.rooms[j].id
        for i, j in pairs
        if weights[i][j] >= ROOM_MATCH_IOU
    }
    return score, mapping, weights


def _wall_f1(plan: FloorPlan, truth: HoldoutTruth) -> float:
    predicted_lines = [_line(wall.start_px, wall.end_px) for wall in plan.walls]
    expected_lines = [_line(wall.start_px, wall.end_px) for wall in truth.walls]
    predicted = unary_union(predicted_lines) if predicted_lines else GeometryCollection()
    expected = unary_union(expected_lines) if expected_lines else GeometryCollection()
    if predicted.is_empty and expected.is_empty:
        return 1.0
    tolerance = WALL_TOLERANCE_RATIO * max(truth.image_width_px, truth.image_height_px)
    covered_prediction = predicted.intersection(expected.buffer(tolerance, cap_style=2)).length
    covered_truth = expected.intersection(predicted.buffer(tolerance, cap_style=2)).length
    precision = covered_prediction / predicted.length if predicted.length else 0.0
    recall = covered_truth / expected.length if expected.length else 0.0
    return 2 * precision * recall / (precision + recall) if precision + recall else 0.0


def _bbox_iou(left: BBox, right: BBox) -> float:
    a = box(left.x0, left.y0, left.x1, left.y1)
    b = box(right.x0, right.y0, right.x1, right.y1)
    return a.intersection(b).area / a.union(b).area


def _opening_f1(plan: FloorPlan, truth: HoldoutTruth) -> float:
    weights = [
        [
            _bbox_iou(predicted.bbox_px, expected.bbox_px)
            if predicted.element_type == expected.element_type
            else 0.0
            for expected in truth.openings
        ]
        for predicted in plan.openings
    ]
    pairs = _max_assignment(weights)
    true_positive = sum(weights[i][j] >= OPENING_MATCH_IOU for i, j in pairs)
    return _f1(true_positive, len(plan.openings), len(truth.openings))


def _walkable(element_type: str) -> bool:
    return element_type == "passage" or element_type.endswith("_door")


def _edge(left: str, right: str) -> tuple[str, str]:
    return (left, right) if left <= right else (right, left)


def _adjacency_f1(plan: FloorPlan, truth: HoldoutTruth, room_map: dict[str, str]) -> float:
    expected = {
        _edge(*opening.connects)
        for opening in truth.openings
        if _walkable(opening.element_type)
    }
    predicted = set()
    for opening in plan.openings:
        if not _walkable(opening.element_type) or opening.connects is None:
            continue
        sides = tuple(
            side if side == EXTERIOR else room_map.get(side, f"unmatched:{side}")
            for side in opening.connects
        )
        predicted.add(_edge(*sides))
    return _f1(len(predicted & expected), len(predicted), len(expected))


def _physical_checks(plan: FloorPlan, orthogonal: bool) -> dict[str, Any]:
    rules: dict[str, list[int]] = defaultdict(lambda: [0, 0])

    def check(rule: str, condition: bool) -> None:
        rules[rule][1] += 1
        rules[rule][0] += not condition

    polygons = []
    epsilon = 1e-6 * max(plan.image_width_px, plan.image_height_px)
    for room in plan.rooms:
        polygon = _polygon(room.polygon_px)
        check("valid_room_polygon", polygon.is_valid and polygon.area > 0)
        polygons.append(polygon if polygon.is_valid else make_valid(polygon))
        if orthogonal:
            points = room.polygon_px
            for start, end in zip(points, points[1:] + points[:1], strict=True):
                check(
                    "orthogonal_room_edge",
                    abs(start.x - end.x) <= epsilon or abs(start.y - end.y) <= epsilon,
                )
    for index, left in enumerate(polygons):
        for right in polygons[index + 1 :]:
            overlap = left.intersection(right).area
            check("non_overlapping_rooms", overlap <= 1e-6 * min(left.area, right.area))

    wall_by_id = {wall.id: wall for wall in plan.walls}
    wall_lines = [_line(wall.start_px, wall.end_px) for wall in plan.walls]
    for index, left in enumerate(wall_lines):
        for right in wall_lines[index + 1 :]:
            check("non_overlapping_walls", left.intersection(right).length <= epsilon)

    accessible_rooms: set[str] = set()
    for opening in plan.openings:
        connects = opening.connects
        known_adjacency = (
            connects is not None and UNKNOWN not in connects and connects[0] != connects[1]
        )
        check("known_opening_adjacency", known_adjacency)
        if connects is not None and known_adjacency and _walkable(opening.element_type):
            accessible_rooms.update(side for side in connects if side not in {EXTERIOR, UNKNOWN})

        host = wall_by_id.get(opening.wall_id or "")
        if opening.element_type != "passage":
            check("opening_has_host_wall", host is not None)
        if host is not None:
            line = _line(host.start_px, host.end_px)
            check(
                "opening_on_host_wall",
                line.distance(box(
                    opening.center_px.x - epsilon,
                    opening.center_px.y - epsilon,
                    opening.center_px.x + epsilon,
                    opening.center_px.y + epsilon,
                ))
                <= host.thickness_px,
            )
            # Pixel runs are inclusive while line length is endpoint distance.
            check("opening_fits_host_wall", opening.width_px <= line.length + 1.0 + epsilon)
    for room in plan.rooms:
        check("room_has_access", room.id in accessible_rooms)

    violations = sum(value[0] for value in rules.values())
    checks = sum(value[1] for value in rules.values())
    return {
        "violations": violations,
        "checks": checks,
        "rate": violations / checks if checks else 0.0,
        "by_rule": {
            name: {"violations": value[0], "checks": value[1]}
            for name, value in sorted(rules.items())
        },
    }


def evaluate_case(plan: FloorPlan, truth: HoldoutTruth, case_id: str) -> dict[str, Any]:
    if plan.source_sha256 != truth.image_sha256:
        raise ValueError(f"{case_id}: prediction and truth image hashes differ")
    if (plan.image_width_px, plan.image_height_px) != (
        truth.image_width_px,
        truth.image_height_px,
    ):
        raise ValueError(f"{case_id}: prediction and truth image dimensions differ")
    room_iou, room_map, _weights = _room_scores(plan, truth)
    physical = _physical_checks(plan, truth.orthogonal)
    return {
        "case_id": case_id,
        "source_group": truth.source_group,
        "room_iou": room_iou,
        "wall_f1": _wall_f1(plan, truth),
        "opening_f1": _opening_f1(plan, truth),
        "adjacency_f1": _adjacency_f1(plan, truth, room_map),
        "physical_violation_rate": physical["rate"],
        "physical": physical,
    }


_METRICS = ("room_iou", "wall_f1", "opening_f1", "adjacency_f1")


def _aggregate(cases: list[dict[str, Any]]) -> dict[str, float | int]:
    violations = sum(case["physical"]["violations"] for case in cases)
    checks = sum(case["physical"]["checks"] for case in cases)
    result: dict[str, float | int] = {
        metric: sum(case[metric] for case in cases) / len(cases) for metric in _METRICS
    }
    result.update(
        cases=len(cases),
        physical_violations=violations,
        physical_checks=checks,
        physical_violation_rate=violations / checks if checks else 0.0,
    )
    return result


def build_report(cases: list[dict[str, Any]]) -> dict[str, Any]:
    if not cases:
        raise ValueError("holdout contains no cases")
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for case in cases:
        grouped[case["source_group"]].append(case)
    return {
        "protocol_version": PROTOCOL_VERSION,
        "aggregate": _aggregate(cases),
        "source_groups": {name: _aggregate(group) for name, group in sorted(grouped.items())},
        "cases": cases,
    }


def apply_release_gates(report: dict[str, Any], gates: ReleaseGates) -> list[str]:
    failures = []
    aggregate = report["aggregate"]
    groups = report["source_groups"]
    if aggregate["cases"] < gates.minimum_cases:
        failures.append(f"cases {aggregate['cases']} < {gates.minimum_cases}")
    if len(groups) < gates.minimum_source_groups:
        failures.append(f"source_groups {len(groups)} < {gates.minimum_source_groups}")

    scopes = {"aggregate": aggregate, **{f"source:{name}": value for name, value in groups.items()}}
    for scope, metrics in scopes.items():
        for metric in _METRICS:
            minimum = getattr(gates, metric)
            if metrics[metric] < minimum:
                failures.append(f"{scope}.{metric} {metrics[metric]:.4f} < {minimum:.4f}")
        maximum = gates.physical_violation_rate
        if metrics["physical_violation_rate"] > maximum:
            failures.append(
                f"{scope}.physical_violation_rate "
                f"{metrics['physical_violation_rate']:.4f} > {maximum:.4f}"
            )
    return failures


def _prediction_truth_pairs(predictions: Path, truths: Path) -> list[tuple[str, Path, Path]]:
    if predictions.is_file() and truths.is_file():
        return [(truths.stem, predictions, truths)]
    if not predictions.is_dir() or not truths.is_dir():
        raise ValueError("predictions and truths must both be JSON files or both be directories")
    predicted = {path.name: path for path in predictions.glob("*.json")}
    expected = {path.name: path for path in truths.glob("*.json")}
    if predicted.keys() != expected.keys():
        missing = sorted(expected.keys() - predicted.keys())
        extra = sorted(predicted.keys() - expected.keys())
        raise ValueError(f"prediction/truth filenames differ; missing={missing}, extra={extra}")
    return [(Path(name).stem, predicted[name], expected[name]) for name in sorted(expected)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="roomify-eval",
        description="Evaluate Roomify JSON predictions against an external holdout.",
    )
    parser.add_argument("predictions", type=Path, help="prediction JSON file or directory")
    parser.add_argument("truths", type=Path, help="truth JSON file or directory")
    parser.add_argument("--gates", type=Path, help="release gate JSON; exit 2 when it fails")
    parser.add_argument("-o", "--output", type=Path, help="write report JSON here")
    args = parser.parse_args(argv)
    failures: list[str] = []

    try:
        cases = []
        for case_id, prediction_path, truth_path in _prediction_truth_pairs(
            args.predictions, args.truths
        ):
            plan = FloorPlan.model_validate_json(prediction_path.read_text(encoding="utf-8"))
            truth = HoldoutTruth.model_validate_json(truth_path.read_text(encoding="utf-8"))
            cases.append(evaluate_case(plan, truth, case_id))
        report = build_report(cases)
        if args.gates:
            gates = ReleaseGates.model_validate_json(args.gates.read_text(encoding="utf-8"))
            failures = apply_release_gates(report, gates)
            report["release_gate"] = {"passed": not failures, "failures": failures}
        payload = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
        if args.output:
            args.output.write_text(payload, encoding="utf-8")
        else:
            print(payload, end="")
    except (OSError, ValueError) as exc:
        print(f"roomify-eval: {exc}", file=sys.stderr)
        return 1

    return 2 if args.gates and failures else 0


if __name__ == "__main__":
    sys.exit(main())
